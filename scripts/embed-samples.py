"""Embed the sample PNGs from examples/ into samples.js as data URIs.

Why: the "Try a sample" buttons must also work when index.html is opened straight
from disk (file://), where browsers block fetch() of local files.

Usage (from the repo root):  python scripts/embed-samples.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SAMPLES = [
    ("sample-badge.png", "Mountain badge", "Flat shapes, 5 colours"),
    ("sample-icon.png", "Chat icon", "2 colours, transparent"),
    ("sample-mark.png", "Wave mark", "Solid background"),
]

lines = [
    "/* Generated by scripts/embed-samples.py. Do not edit by hand.",
    " * Sample PNGs embedded as data URIs so 'Try a sample' also works from file://. */",
    "window.SAMPLE_FILES = [",
]
for name, label, hint in SAMPLES:
    data = base64.b64encode((ROOT / "examples" / name).read_bytes()).decode()
    lines.append(
        f"  {{ file: '{name}', label: '{label}', hint: '{hint}', src: 'examples/{name}',\n"
        f"    data: 'data:image/png;base64,{data}' }},"
    )
lines.append("];\n")
(ROOT / "samples.js").write_text("\n".join(lines), encoding="utf-8", newline="\n")
print("samples.js written")
